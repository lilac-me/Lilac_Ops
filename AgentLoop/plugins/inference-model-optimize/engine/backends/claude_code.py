# Claude Code Backend
# ===================
# Claude Code runs workflows in a sandboxed JS runtime (Workflow JS).
# The Python state machine cannot be called directly from inside a workflow.
#
# This backend provides:
#   1. A CLI wrapper for offline use (testing, CI, auditing).
#   2. A YAML → JS compiler that generates state-machine-config.js, a
#      lightweight JS equivalent of the YAML state machine for use inside
#      Claude Code Workflow JS.
#
# Usage:
#   # Compile YAML to JS for Workflow runtime
#   python -m engine.backends.claude_code compile \
#       --yaml plugins/inference-model-optimize/workflows/optimize-pipeline.yaml \
#       --out plugins/inference-model-optimize/workflows/state-machine-config.js

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from engine.backends.base import AbstractBackend, AgentResult

# Import from sibling modules
_HERE = Path(__file__).resolve().parent
_ENGINE = _HERE.parent
if str(_ENGINE) not in sys.path:
    sys.path.insert(0, str(_ENGINE))


class ClaudeCodeBackend(AbstractBackend):
    """Claude Code backend.

    In Claude Code, agent spawning is handled by the Workflow JS runtime's
    built-in `agent()` function — this Python backend cannot directly spawn
    agents. Use the YAML→JS compiler to generate a runtime-compatible
    state machine configuration.
    """

    def platform_name(self) -> str:
        return "claude-code"

    def available_agents(self) -> list[str]:
        # Agents are discovered from plugins/<plugin>/agents/AGENT.md files
        # by the Claude Code plugin system.
        return [
            "inference-model-optimize:orchestrator:orchestrator",
            "inference-model-optimize:architect:architect",
            "inference-model-optimize:developer:developer",
            "inference-model-optimize:tester:tester",
            "inference-model-optimize:reviewer:reviewer",
            "inference-model-optimize:optimizer:optimizer",
        ]

    def spawn_agent(
        self,
        agent_type: str,
        prompt: str,
        schema: dict[str, Any] | None = None,
        workspace: Path | None = None,
        label: str = "",
    ) -> AgentResult:
        """Not supported in Python — Claude Code agents are spawned by Workflow JS."""
        raise RuntimeError(
            "ClaudeCodeBackend: agent spawning is handled by the Workflow JS runtime. "
            "Use the YAML→JS compiler to generate a runtime-compatible state machine, "
            "then call agent() inside your .workflow.js file."
        )


# ---------------------------------------------------------------------------
# YAML → JS Compiler
# ---------------------------------------------------------------------------

def compile_yaml_to_js(yaml_path: str | Path, out_path: str | Path) -> str:
    """Compile a pipeline YAML to a JavaScript state machine config module.

    The generated JS file exports a STATE_MACHINE constant that the
    Workflow JS can import and use for deterministic state transitions.

    Args:
        yaml_path: Path to the pipeline YAML file.
        out_path: Path to write the generated JS file.

    Returns:
        The generated JS source as a string.
    """
    from engine.state_machine import load_state_machine

    sm = load_state_machine(yaml_path)
    pipeline = sm.get("pipeline", {})
    states = sm.get("states", []) or sm.get("phase_o4_states", [])

    js_lines = [
        "// Auto-generated by engine/backends/claude_code.py compile",
        f"// Source: {Path(yaml_path).as_posix()}",
        "// DO NOT EDIT MANUALLY — edit the YAML and recompile.",
        "",
        "export const STATE_MACHINE = {",
        f"  pipelineName: {json.dumps(pipeline.get('name', ''))},",
        f"  version: {json.dumps(pipeline.get('version', ''))},",
        f"  initial: {json.dumps(pipeline.get('initial_state', 'await_worker'))},",
        f"  totalSpawnCap: {json.dumps(pipeline.get('total_spawn_cap', 20))},",
        f"  terminal: {json.dumps(['done', 'abort'])},",
        f"  pause: {json.dumps(['await_user_decision'])},",
        "  states: {",
    ]

    # Compile each state
    for state in states:
        sid = state["id"]
        agent = state.get("agent")
        iter_cap_val = state.get("iter_cap", 999)
        iter_counter = state.get("iter_counter", sid)

        # Build full agent type
        if agent and ":" not in str(agent):
            # Short name → resolve to qualified Claude Code agent type
            plugin_name = pipeline.get("name", "inference-model-optimize")
            agent_type = f"{plugin_name}:{agent}:{agent}"
        else:
            agent_type = agent

        js_lines.append(f"    {json.dumps(sid)}: {{")
        js_lines.append(f"      agent: {json.dumps(agent_type)},")
        js_lines.append(f"      iterCap: {json.dumps(iter_cap_val)},")
        js_lines.append(f"      iterCounter: {json.dumps(iter_counter)},")
        js_lines.append("      exitTransitions: [")

        for trans in state.get("exit_transitions", []):
            cond = trans.get("condition", {})
            goto = trans.get("goto", "abort")
            rationale = trans.get("rationale", "")
            js_lines.append("        {")
            js_lines.append(f"          condition: {json.dumps(cond)},")
            js_lines.append(f"          goto: {json.dumps(goto)},")
            js_lines.append(f"          rationale: {json.dumps(rationale)}")
            js_lines.append("        },")

        js_lines.append("      ],")
        js_lines.append("    },")

    js_lines.append("  },")
    js_lines.append("};")
    js_lines.append("")

    js_source = "\n".join(js_lines)

    # Write output
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(js_source, encoding="utf-8")

    return js_source


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def _main():
    import argparse

    ap = argparse.ArgumentParser(
        description="Claude Code backend — YAML→JS compiler + offline tools"
    )
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_compile = sub.add_parser("compile", help="Compile pipeline YAML to Workflow JS config")
    p_compile.add_argument("--yaml", required=True, type=Path, help="Path to pipeline YAML")
    p_compile.add_argument("--out", required=True, type=Path, help="Output JS file path")

    args = ap.parse_args()

    if args.cmd == "compile":
        source = compile_yaml_to_js(args.yaml, args.out)
        print(f"Compiled: {args.yaml} → {args.out}")
        print(f"  {source.count(chr(10))} lines generated")


if __name__ == "__main__":
    _main()
